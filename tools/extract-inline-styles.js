// PizzaCRM — One-shot asset extraction
// ─────────────────────────────────────────
// Moves inline <style> blocks from index.html → public/styles.css
// Moves inline JSON-LD <script type="application/ld+json"> → public/schema.json
//
// Why this exists:
//  * The CSP for production (server/index.js) drops 'unsafe-inline' from
//    both script-src and style-src, so inline <style> and inline script
//    content (incl. JSON-LD) stop being accepted by the browser.
//  * Re-running this script is a no-op (no <style> / no JSON-LD found).
//
// How to re-run if you ever need to re-inline for some reason:
//    node tools/extract-inline-styles.js --revert    # restores from public/*.css|json
//
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const htmlPath = path.join(root, 'index.html');
const cssPath = path.join(root, 'public', 'styles.css');
const schemaPath = path.join(root, 'public', 'schema.json');

const REVERT = process.argv.includes('--revert');

let html = fs.readFileSync(htmlPath, 'utf-8');
let log = [];

if (REVERT) {
  // Revert: public/styles.css → <style>; public/schema.json → <script type="application/ld+json">
  if (fs.existsSync(cssPath)) {
    const css = fs.readFileSync(cssPath, 'utf-8');
    html = html.replace(
      /<link\s+rel=["']stylesheet["']\s+href=["']\/styles\.css["']\s*\/?>/i,
      `<style>\n${css}\n</style>`
    );
    log.push('REVERT styles.css → <style>');
  }
  if (fs.existsSync(schemaPath)) {
    const json = fs.readFileSync(schemaPath, 'utf-8');
    html = html.replace(
      /<script\s+type=["']application\/ld\+json["']\s+src=["']\/schema\.json["']>\s*<\/script>/i,
      `<script type="application/ld+json">\n${json}\n</script>`
    );
    log.push('REVERT schema.json → <script type="application/ld+json">');
  }
  fs.writeFileSync(htmlPath, html);
  console.log(log.join(' '));
  process.exit(0);
}

// ── 1) Extract all <style> blocks → public/styles.css ────────────────────
const styleRe = /<style[^>]*>([\s\S]*?)<\/style>/gi;
const styleBlocks = [];
{
  let m;
  while ((m = styleRe.exec(html)) !== null) styleBlocks.push(m[1]);
}

if (styleBlocks.length > 0) {
  const cssOut =
    '/* =============================================\n' +
    '   PizzaCRM — styles extracted from index.html\n' +
    '   Generated by tools/extract-inline-styles.js\n' +
    '   ============================================= */\n\n' +
    styleBlocks.join('\n\n/* ---- next block ---- */\n\n');

  fs.mkdirSync(path.dirname(cssPath), { recursive: true });
  fs.writeFileSync(cssPath, cssOut);
  log.push(`EXTRACTED ${styleBlocks.length} <style> block(s) → public/styles.css`);

  // Dedup: FIRST <style> → <link>, subsequent → removed entirely.
  let replacedFirst = false;
  html = html.replace(/<style[^>]*>[\s\S]*?<\/style>/gi, () => {
    if (!replacedFirst) {
      replacedFirst = true;
      return '<link rel="stylesheet" href="/styles.css">';
    }
    return '';
  });
  log.push('REPLACED <style> with single <link> (deduped)');
} else {
  const hasLink = /<link\s+rel=["']stylesheet["']\s+href=["']\/styles\.css["']/i.test(html);
  if (!hasLink) {
    html = html.replace('</head>', '  <link rel="stylesheet" href="/styles.css">\n</head>');
    log.push('INSERTED <link rel="stylesheet" href="/styles.css">');
  } else {
    log.push('NO_ACTIONS_STYLES (already extracted)');
  }
}

// ── 2) Extract JSON-LD <script> → public/schema.json ─────────────────────
// `<script type="application/ld+json">{…}</script>` is blocked by prod CSP
// (script-src no longer permits inline content). External JSON served via
// `<script … src="/schema.json">` is fetched under 'self' (allowed).
const jsonLdRe = /<script\s+type=["']application\/ld\+json["']>([\s\S]*?)<\/script>/i;
const jsonLdMatch = html.match(jsonLdRe);
if (jsonLdMatch) {
  let jsonText = jsonLdMatch[1].trim();
  // Strip the redundant @context duplicate if present (harmless either way)
  try {
    const parsed = JSON.parse(jsonText);
    fs.mkdirSync(path.dirname(schemaPath), { recursive: true });
    fs.writeFileSync(schemaPath, JSON.stringify(parsed, null, 2));
    log.push('EXTRACTED 1 JSON-LD → public/schema.json');
  } catch (e) {
    console.error('JSON-LD parse failed; keeping inline. Error:', e.message);
    log.push('JSON-LD_PARSE_FAILED_KEPT_INLINE');
    fs.writeFileSync(htmlPath, html);
    process.exit(1);
  }
  html = html.replace(jsonLdRe, '<script type="application/ld+json" src="/schema.json"></script>');
  log.push('REPLACED JSON-LD inline with <script src="/schema.json">');
} else if (!fs.existsSync(schemaPath)) {
  log.push('NO_JSON_LD_TO_EXTRACT (and no schema.json yet)');
} else {
  log.push('NO_ACTIONS_JSONLD (already external)');
}

fs.writeFileSync(htmlPath, html);
console.log(log.join(' | '));
